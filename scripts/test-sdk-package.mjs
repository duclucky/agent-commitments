import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile, copyFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { npmCliPath } from "./npm-cli.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)),"..");
const metadata=JSON.parse(await readFile(join(root,".release/sdk-release.json"),"utf8"));
const consumer=await mkdtemp(join(root,".release/consumer-"));
await writeFile(join(consumer,"package.json"),JSON.stringify({name:"external-sdk-consumer",private:true,type:"module"}));
const npmCli=await npmCliPath();
const run=(command,args,cwd)=>{
  const result=spawnSync(command,args,{cwd,encoding:"utf8"});
  if(result.status!==0) throw new Error(`${command} failed: ${result.stderr || result.stdout}`);
  return result.stdout;
};
run(process.execPath,[npmCli,"install","--ignore-scripts","--no-audit","--no-fund",join(root,".release",metadata.filename)],consumer);
const installed=JSON.parse(await readFile(join(consumer,"node_modules/@agent-commitments/sdk/package.json"),"utf8"));
assert.equal(installed.dependencies["@agent-commitments/network-config"],undefined);
assert.equal(installed.version,"0.1.0-alpha.1");
await copyFile(join(root,"examples/sdk-starter/index.mjs"),join(consumer,"index.mjs"));
const output=JSON.parse(run(process.execPath,["index.mjs"],consumer));
assert.equal(output.mode,"prepare-only");assert.equal(output.call.chainId,5042002);
assert.equal(output.call.value,"0");assert.match(output.call.data,/^0x[0-9a-f]+$/i);
await writeFile(join(consumer,"consumer.ts"),`import {createArcTestnetClient,createArcMainnetPilotClient,arcMainnetPilotDeployment,type PreparedCall} from '@agent-commitments/sdk';
const call:PreparedCall=createArcTestnetClient().prepareDeposit(1_000_000n);
const pilot=createArcMainnetPilotClient();
const address:string=arcMainnetPilotDeployment.budgetVault;
export {call,pilot,address};\n`);
run(process.execPath,[join(root,"node_modules/typescript/bin/tsc"),"consumer.ts","--noEmit","--strict","--target","ES2022","--module","NodeNext","--moduleResolution","NodeNext","--skipLibCheck"],consumer);
console.log(`Standalone SDK package passed: isolated npm install, ESM starter and TypeScript declarations (${metadata.version}).`);
